// Build the public redirect table for every app route in src/App.tsx (no hand-typed list):
//   1. the route's static guide page (APP_CANONICAL, aliases)       — handled in seoRoutes.publicTarget
//   2. an approved override (ROUTE_OVERRIDES), or /in-the-app (IN_APP_SCREENS)
//   3. otherwise the category page of the tool in the registry (calculatorList.ts)
// Routes with an ID (/scheme/:id, /my-loans/:id …) are matched in seoRoutes.publicTarget.
// Throws if an app route would be left without a target, so a new screen cannot silently
// fall through to "/".
import fs from 'node:fs';
import { buildSync } from 'esbuild';

const load = async (entry) => {
    const out = buildSync({ entryPoints: [entry], bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'error', loader: { '.json': 'json' } });
    return import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'));
};

export async function buildRouteTargets() {
    const R = await load('src/landing/seoRoutes.ts');
    const { allCalcs, appTools } = await load('src/data/calculatorList.ts');
    const { siteCategory } = await load('src/landing/categories.ts');
    const { schemes } = await load('src/data/schemes.ts');
    const src = fs.readFileSync('src/App.tsx', 'utf8');
    const routes = [...new Set([...src.matchAll(/<Route path="([^"]+)"/g)].map((m) => m[1]))];
    const registry = new Map([...allCalcs, ...appTools].map((c) => [c.path, c]));
    const exact = {};
    const uncovered = [];
    for (const r of routes) {
        if (r === '*' || r === '/' || r.includes(':')) continue;
        if (R.STATIC_PAGES.includes(r.slice(1)) || R.LEGAL_PAGES.includes(r.slice(1)) || R.SHARED_PAGES.includes(r)) continue;
        if (R.APP_CANONICAL[R.APP_ALIASES[r] ?? r]) continue;
        if (R.publicTarget(r, {}, [])) continue;   // covered by a pattern (/profile/*, /expenses/credit-cards/*)
        const target = R.APP_ALIASES[r] ?? r;
        if (R.ROUTE_OVERRIDES[target]) exact[r] = R.ROUTE_OVERRIDES[target];
        else if (R.IN_APP_SCREENS.includes(target)) exact[r] = R.IN_THE_APP;
        else if (registry.has(target)) exact[r] = R.categoryPath(siteCategory(registry.get(target)));
        else uncovered.push(r);
    }
    // Every route with an ID must be matched by publicTarget().
    for (const r of routes.filter((x) => x.includes(':'))) {
        const sample = r.replace(/:[a-zA-Z]+/g, 'x1');
        if (!R.publicTarget(sample, exact, [])) uncovered.push(r);
    }
    if (uncovered.length) throw new Error(`app routes without a public target: ${uncovered.join(', ')} (add them to ROUTE_OVERRIDES or IN_APP_SCREENS in src/landing/seoRoutes.ts)`);
    const sorted = Object.fromEntries(Object.entries(exact).sort(([a], [b]) => a.localeCompare(b)));
    const ids = schemes.map((s) => s.id).sort();
    const text = `// Generated by scripts/landing/sync-vercel-headers.mjs from src/App.tsx, the calculator\n// registry and schemes.ts. Do not edit by hand.\nexport const ROUTE_TARGETS: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 4)};\n\nexport const SCHEME_IDS: readonly string[] = ${JSON.stringify(ids, null, 4)};\n`;
    return { text, count: Object.keys(sorted).length, routes };
}
