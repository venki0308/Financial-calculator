// Writes the website's module indexes, so new pages, calculators and scheme content are added by
// creating one file each (no shared registry edits):
//   src/landing/features/generated.ts         every page module + every calculator (server render)
//   src/landing/features/generated-client.ts  one lazy loader per calculator (browser; one chunk each)
//   src/landing/schemes/generated.ts          website-only scheme content, by scheme id
// Sources: src/landing/features/pages/*.tsx, src/landing/features/calcs/c/*.tsx,
// src/landing/schemes/content/*.ts. Files whose name starts with "_" are drafts and are skipped.
// Run by `npm run build:landing`; `--check` fails if any index is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const rel = (...p) => path.join(ROOT, ...p);
const list = (dir, ext) => (fs.existsSync(rel(dir)) ? fs.readdirSync(rel(dir)) : [])
    .filter((f) => f.endsWith(ext) && !f.startsWith('_') && !f.endsWith('.d.ts')).map((f) => f.slice(0, -ext.length)).sort();
const ident = (s) => s.replace(/[^A-Za-z0-9]/g, '_');
const HEAD = '// GENERATED by scripts/landing/gen-feature-index.mjs — do not edit. Add a file instead.\n';

const pages = list('src/landing/features/pages', '.tsx');
const calcs = list('src/landing/features/calcs/c', '.tsx');
const schemes = list('src/landing/schemes/content', '.ts');

const out = {
    'src/landing/features/generated.ts': HEAD +
        pages.map((p) => `import * as p_${ident(p)} from './pages/${p}';`).join('\n') + '\n' +
        calcs.map((c) => `import c_${ident(c)} from './calcs/c/${c}';`).join('\n') + '\n' +
        `import type { ComponentType } from 'react';\n\n` +
        `/** Every module in features/pages (each exports one FeatureDef). */\n` +
        `export const PAGE_MODULES: ReadonlyArray<Record<string, unknown>> = [${pages.map((p) => `p_${ident(p)}`).join(', ')}];\n\n` +
        `/** Calculators in features/calcs/c, by file name (= CalcKey). */\n` +
        `// eslint-disable-next-line @typescript-eslint/no-explicit-any\n` +
        `export const CALC_COMPONENTS: Readonly<Record<string, ComponentType<any>>> = {\n${calcs.map((c) => `    '${c}': c_${ident(c)},`).join('\n')}\n};\n`,
    'src/landing/features/generated-client.ts': HEAD +
        `import type { ComponentType } from 'react';\n\n` +
        `/** One lazily loaded chunk per calculator in features/calcs/c (the 9 batch-1 calculators live in calcs/all.tsx). */\n` +
        `// eslint-disable-next-line @typescript-eslint/no-explicit-any\n` +
        `export const CALC_LOADERS: Readonly<Record<string, () => Promise<{ default: ComponentType<any> }>>> = {\n${calcs.map((c) => `    '${c}': () => import('./calcs/c/${c}'),`).join('\n')}\n};\n`,
    'src/landing/schemes/generated.ts': HEAD +
        schemes.map((s) => `import s_${ident(s)} from './content/${s}';`).join('\n') + '\n' +
        `import type { SchemeContent } from './types';\n\n` +
        `/** Website-only scheme content, by scheme id (schemes/content/<id>.ts). */\n` +
        `export const SCHEME_CONTENT: Readonly<Record<string, SchemeContent>> = {\n${schemes.map((s) => `    '${s}': s_${ident(s)},`).join('\n')}\n};\n`,
};

const check = process.argv.includes('--check');
let stale = 0;
for (const [file, text] of Object.entries(out)) {
    const cur = fs.existsSync(rel(file)) ? fs.readFileSync(rel(file), 'utf8') : '';
    if (cur === text) continue;
    if (check) { console.error(`stale: ${file}`); stale++; } else { fs.mkdirSync(path.dirname(rel(file)), { recursive: true }); fs.writeFileSync(rel(file), text); }
}
if (check && stale) process.exit(1);
console.log(`gen-feature-index: ${pages.length} pages, ${calcs.length} calculators, ${schemes.length} scheme content files${check ? ' (up to date)' : ''}`);
